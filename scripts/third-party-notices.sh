#!/usr/bin/env bash
# Writes THIRD_PARTY_NOTICES.md: the license of every module compiled into
# Wera's binaries (and of the Go standard library), copied from the module
# cache. Those licenses keep applying to that code. Run after changing
# dependencies; it fails on a module whose license it can't find or on a
# copyleft license, which Wera must not ship.
#
# Usage: scripts/third-party-notices.sh
set -euo pipefail
cd "$(dirname "$0")/.."

modcache=$(go env GOMODCACHE)
out=THIRD_PARTY_NOTICES.md
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

# Module paths in the cache escape capitals as !lowercase.
escape() { sed -E 's/[A-Z]/!\L&/g' <<<"$1"; }

licence_file() {
	find "$1" -maxdepth 1 -type f \( -iname 'licen[cs]e*' -o -iname 'copying*' \) | sort | head -1
}

{
	echo "# Third-party notices"
	echo
	echo "Wera's own code is proprietary (see LICENSE). Its binaries include the"
	echo "open-source modules below, each under its own license, reproduced here."
	echo "Generated by scripts/third-party-notices.sh; do not edit by hand."
	echo
	gostd=$(go env GOROOT)/LICENSE
	echo "## Go standard library ($(go env GOVERSION))"
	echo
	echo '```'
	cat "$gostd"
	echo '```'
	echo
	go list -deps -f '{{if not .Standard}}{{with .Module}}{{.Path}} {{.Version}}{{end}}{{end}}' ./cmd/... |
		sort -u | grep -v '^wera ' | while read -r path version; do
		dir="$modcache/$(escape "$path")@$(escape "$version")"
		file=$(licence_file "$dir")
		if [[ -z "$file" ]]; then
			echo "no license file for $path $version" >&2
			exit 1
		fi
		if grep -qiE 'GNU (AFFERO |LESSER )?GENERAL PUBLIC LICENSE' "$file"; then
			echo "copyleft license in $path $version: $file" >&2
			exit 1
		fi
		echo "## $path $version"
		echo
		echo '```'
		cat "$file"
		echo '```'
		echo
		# Apache-2.0 asks for the NOTICE file to travel with the code.
		if [[ -f "$dir/NOTICE" ]]; then
			echo '```'
			cat "$dir/NOTICE"
			echo '```'
			echo
		fi
	done
} >"$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "wrote $out"
